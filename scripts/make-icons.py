def main():
    names = list(ICONS)
    img = Image.new('RGBA', (8 * len(names), 8), (0, 0, 0, 0))
    px = img.load()
    for i, name in enumerate(names):
        rows = ICONS[name]
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), name
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == '#':
                    px[i * 8 + x, y] = (255, 255, 255, 255)
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'client')
    img.save(os.path.join(root, 'public', 'icons.png'))
    with open(os.path.join(root, 'src', 'icons.gen.ts'), 'w', encoding='utf8', newline='\n') as fh:
        fh.write('// Written by scripts/make-icons.py. Do not edit by hand.\n')
        fh.write('export const ICON_NAMES = [' + ', '.join(f"'{n}'" for n in names) + '] as const;\n')
    art = os.path.join(root, '..', 'art')
    img.resize((img.width * 4, 32), Image.NEAREST).save(os.path.join(art, 'icons-preview.png'))
    print('wrote', len(names), 'icons')


if __name__ == '__main__':
    main()
