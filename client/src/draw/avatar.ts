      const hem: Span[] = range(1, 6).map((i) => [hip + i, x0 - (i >= 3 ? 1 : 0), x1 + (i >= 3 ? 1 : 0)] as Span);
      t.part(hem, mat, '', 'rb', [CX, top]);
