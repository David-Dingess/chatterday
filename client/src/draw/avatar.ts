/** A skirt from the front or the back, over legs that are already drawn. */
function skirtFront(c: Cv, p: Person, hip: number, sit: boolean) {
  const hw = p.hw ?? p.tw, long = p.bottom === 'longskirt';
  const xa = CX - hw, xb = CX + hw - 1;
  if (sit) {
    const [, seat] = seatOf(p);
    c.part(span(xa, hip + 1, seat + 1, xb), new Mat(p.pants.hi, { lo: p.pants.base }), '', 'rb');      // the lap
    c.part(long ? span(xa + 1, seat + 1, FEET - 1, xb - 1) : [[seat + 1, xa, xb]], p.pants, '', 'rb');
    return;
  }
  const end = long ? FEET - 3 : hip + 4, n = end - hip;
  const spans: Span[] = [];
  for (let i = 1; i <= n; i++) {
    const out = i === 1 ? -1 : i >= 3 && (!long || i > n - 3) ? 1 : 0;        // tucked in at the waist, flared at the hem
    spans.push([hip + i, xa - out, xb + out]);
  }
  c.part(spans, p.pants, '', 'rb');
  for (let x = xa + 2; x < xb; x += 3) for (let y = hip + 2; y < end; y++) c.px(x, y, p.pants.lo);    // pleats
}

const STRAP: RGB = [44, 44, 54];
const DIGITS = ['111101101101111', '010110010010111', '111001111100111', '111001111001111', '101101111001001', '111100111001111', '111100111101111', '111001001010010', '111101111101111', '111101111001111'];
/** A number in 3-by-5 digits, its middle at x. */
function numberAt(c: Cv, n: number, x: number, y: number, col: RGB) {
  const text = String(n);
  let x0 = x - Math.floor((text.length * 4 - 1) / 2);
  for (const ch of text) {
    const d = DIGITS[Number(ch)];
    for (let i = 0; i < 15; i++) if (d[i] === '1') c.px(x0 + (i % 3), y + Math.floor(i / 3), col);
    x0 += 4;
  }
}
