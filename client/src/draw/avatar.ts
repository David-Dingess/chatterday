// Draws a character's sprite sheet, dot by dot, from the look somebody built. Frames are 48 by 48, and over every
// frame there are SPRITE_UP rows of headroom, so a cell of the sheet is 48 wide and 48 + SPRITE_UP tall. A sheet has
// one row per animation (SPRITE_ROWS), four frames each, and then the same four again with the mouth open for talking.
// Shapes are hand-placed rows of dots on a small head layer (26 wide) that is pasted over the body.

