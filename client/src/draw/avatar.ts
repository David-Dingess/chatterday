/** A shape on the head layer: rows of dots, and single dots that get a tone of their own (H lit, g shaded, ...). */
type Shape = { spans: Span[]; marks: (readonly [number, number, string])[] };
const plain = (spans: Span[], hi: (readonly [number, number])[] = []): Shape => ({ spans, marks: hi.map(([y, x]) => [x, y, 'H'] as const) });
const NONE: Shape = { spans: [], marks: [] };

/** Rows that were typed the wrong width: the test checks this stays empty. */
export const ART_FAULTS: string[] = [];

/** Reads a shape from rows of text, the first row at y0. '.' is empty, '#' is filled and shaded like the rest, and a
 *  letter is filled and then given the tone that letter stands for. */
function art(y0: number, lines: string[]): Shape {
  const spans: Span[] = [], marks: [number, number, string][] = [];
  lines.forEach((line, i) => {
    if (line.length !== HW) ART_FAULTS.push(`row ${y0 + i} is ${line.length} wide: ${line}`);
    let start = -1;
    for (let x = 0; x <= line.length; x++) {
      const on = x < line.length && line[x] !== '.' && line[x] !== ' ';
      if (on && start < 0) start = x;
      if (!on && start >= 0) { spans.push([y0 + i, start, x - 1]); start = -1; }
      if (on && line[x] !== '#') marks.push([x, y0 + i, line[x]]);
    }
  });
  return { spans, marks };
}
const mirror = (s: Shape): Shape => ({ spans: s.spans.map(([y, a, b]) => [y, HW - 1 - b, HW - 1 - a] as Span), marks: s.marks.map(([x, y, ch]) => [HW - 1 - x, y, ch] as const) });
/** The same rows of text moved to the right: the side of the head sits one dot further over than the front. */
const sh = (lines: string[], dx = 1) => lines.map((l) => ('.'.repeat(dx) + l).slice(0, HW));
const join = (...shapes: Shape[]): Shape => ({ spans: shapes.flatMap((s) => s.spans), marks: shapes.flatMap((s) => s.marks) });
const minY = (spans: readonly Span[]) => Math.min(...spans.map((s) => s[0]));

