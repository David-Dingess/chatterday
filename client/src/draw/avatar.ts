const patDots = (col: RGB): Pattern => (dx, dy, c) => ((pm(dx, 4) === 0 && pm(dy, 4) === 0) || (pm(dx, 4) === 2 && pm(dy, 4) === 2) ? col : c);
const patStripes: Pattern = (_dx, dy, c) => (pm(dy, 2) === 1 ? mix(c, WHITE, 0.32) : c);
const patQuilt: Pattern = (_dx, dy, c, m) => (pm(dy, 3) === 2 ? m.lo : c);
const patCheck: Pattern = (dx, dy, c) => (pm(dx, 2) === 0 && pm(dy, 2) === 0 ? mix(c, WHITE, 0.5) : c);
const patHoops = (two: RGB): Pattern => (_dx, dy, c) => (pm(dy, 4) >= 2 ? two : c);
const patPins: Pattern = (dx, _dy, c) => (pm(dx, 3) === 0 ? mix(c, WHITE, 0.3) : c);
const patPlaid = (two: RGB): Pattern => (dx, dy, c) => {
  const a = pm(dx, 4) === 0, b = pm(dy, 4) === 0;
  return a && b ? mix(two, SHADE, 0.3) : a || b ? mix(c, two, 0.65) : c;
};
const patBlock = (two: RGB): Pattern => (_dx, dy, c) => (dy >= 6 ? two : c);
const patSplit = (two: RGB): Pattern => (dx, _dy, c) => (dx >= 0 ? two : c);
/** Bands of colour winding out from the middle of the chest. */
const patTieDye = (two: RGB): Pattern => (dx, dy, c) => {
  const x = dx + 0.5, y = dy - 5;
  const band = pm(Math.floor((Math.sqrt(x * x + y * y) + Math.atan2(y, x) * (6 / Math.PI)) / 1.6), 4);
  return band === 0 ? c : band === 1 ? mix(c, two, 0.55) : band === 2 ? two : mix(two, WHITE, 0.45);
};
/** Blotches in three tones, two dots square and staggered like bricks. */
const patCamo = (two: RGB): Pattern => (dx, dy, c) => {
  const a = Math.floor(dx / 2), b = Math.floor((dy + pm(a, 2)) / 2);
  const v = pm(a * 7 + b * 13 + a * b, 5);
  return v === 0 ? mix(c, SHADE, 0.4) : v === 1 ? mix(c, two, 0.6) : c;
};
// Hair textures. They are given whole-head positions, so a texture can start part of the way down.
// Curls: light and dark flecks, staggered.
const texCurl: Pattern = (dx, dy, c, m) => (pm(dx, 4) === 1 && pm(dy, 4) === 0 ? mix(c, m.hi, 0.7) : pm(dx, 4) === 3 && pm(dy, 4) === 2 ? m.lo : c);
const WAVE = [0, 1, 1, 0, -1, -1];
const texWave: Pattern = (dx, dy, c, m) => (dy >= 10 && pm(dx + WAVE[pm(dy, 6)], 5) === 0 ? m.lo : c);
const texStrands: Pattern = (dx, dy, c, m) => (dy >= 11 && pm(dx, 5) === 2 ? m.lo : c);
const texLocs: Pattern = (dx, dy, c, m) => (dy >= 8 && pm(dx, 3) === 0 ? m.lo : c);
const texBraid = (x0: number, x1: number, y0: number): Pattern => (dx, dy, c, m) => (dy >= y0 && dx >= x0 && dx <= x1 && pm(dx + dy, 2) === 0 ? m.lo : c);
// Many thin plaits: a dark line between each, and the weave of each one caught by the light on every other dot.
const texPlaits: Pattern = (dx, dy, c, m) => (pm(dx, 3) === 0 ? m.lo : dy >= 8 && pm(dy + Math.floor(dx / 3), 2) === 0 ? mix(c, m.hi, 0.5) : c);
// Rows braided flat to the head: seen running back from the front (and down the back), and along the side.
const texRowsDown: Pattern = (dx, _dy, c, m) => (pm(dx, 2) === 0 ? m.lo : mix(c, m.hi, 0.35));
const texRowsAlong: Pattern = (_dx, dy, c, m) => (pm(dy, 2) === 0 ? m.lo : mix(c, m.hi, 0.35));
// Short twists: each a dark dot with a lit one beside it, row upon staggered row.
const texTwist: Pattern = (dx, dy, c, m) => { const k = pm(dx + (pm(dy, 4) >= 2 ? 1 : 0), 3); return k === 0 ? m.lo : k === 1 && pm(dy, 2) === 0 ? mix(c, m.hi, 0.6) : c; };
// Waves brushed into a short cut: short dark arcs, each row set off from the last.
const texWaves: Pattern = (dx, dy, c, m) => (pm(dx + pm(dy, 2) * 2, 4) < 2 && pm(dy, 2) === 0 ? m.lo : pm(dx + 1, 4) < 2 && pm(dy, 2) === 1 ? mix(c, m.hi, 0.35) : c);

