const covered =(p: Person) => !!(p.hat && HATS[p.hat].covers);
const hairHidden = (p: Person) => !!(p.hat && HATS[p.hat].covers === 'all');
/** Which hair shapes to use: a cut drawn for under a hat gives way to the full one when the hat comes off. */
const hairKey = (p: Person) => (covered(p) && p.hairCapped ? p.hairCapped : p.hairStyle);

const hatTones = (m: Mat, p: Person): Record<string, RGB> => ({
  h: m.hi, l: m.lo, o: m.base, d: mix(m.lo, SHADE, 0.3), k: mix(m.lo, SHADE, 0.55), w: mix(m.hi, WHITE, 0.6),
  W: [246, 243, 238], v: [207, 200, 214], y: [255, 216, 74], r: [229, 72, 77], b: [79, 156, 240], G: [95, 174, 87], p: [240, 143, 176], K: [44, 40, 56], a: p.accent,
});

/** Headphones worn as a hat: a band over the top and a cup on each ear, in the hat's colour. */
function drawPhones(c: Cv, p: Person, view: 'f' | 's' | 'b', m: Mat) {
  if (view === 's') {
    const spans = styleOf(p).s.spans.filter(([, a, b]) => a <= 15 && 15 <= b);
    for (let y = spans.length ? minY(spans) : 6; y < 11; y++) c.px(16, y, m.hi);
    c.part(span(13, 11, 18, 18), m, 'tl', 'rb');
    c.rect(15, 13, 16, 15, m.lo);
    return;
  }
  const t = Math.max(1, hairTop(p));
  for (let x = 6; x < 20; x++) c.px(x, t - 1, m.hi);
  for (const x of [4, 5, 20, 21]) c.px(x, t, m.base);
  c.px(3, t + 1, m.base); c.px(22, t + 1, m.base);
  for (let y = t + 2; y < 11; y++) { c.px(2, y, m.base); c.px(23, y, m.base); }
  for (const x0 of [1, 22]) { c.part(span(x0, 11, 17, x0 + 2), m, 'tl', 'rb'); if (view === 'f') c.px(x0 + 1, 13, m.hi); }
}

/** Everything but the baseball cap, which has its own drawing in each head. */
function drawHat(c: Cv, p: Person, view: 'f' | 's' | 'b', y1 = 99) {
  const kind = p.hat!;
  const h = HATS[kind];
  const m = p.hatMat ?? PLAIN_HAT;
  if (kind === 'headphones') { drawPhones(c, p, view, m); return; }
  if (h.art) {
    const a = h.art[view];
    const tones = hatTones(m, p);
    c.part(a.spans.filter((s) => s[0] <= y1), m, 't', 'r');                 // y1: in bed, a long covering stops at the chin
    for (const [x, y, ch] of a.marks) if (tones[ch] && y <= y1) c.px(x, y, tones[ch]);
    return;
  }
  let sp = h[view] ?? h.f;
  if (kind === 'party') {
    // A party hat stands on top of the head: its rim one row down into the hair (or the scalp) under its middle,
    // not down round the forehead. Its shape is listed with the rim at row 7, so it is lifted by whatever that
    // takes: up into the headroom over the frame, for anybody with hair of any height.
    const [rim, a, b] = sp.crown[sp.crown.length - 1];
    let under = rim - 1;
    find: for (let y = -c.up; y < c.h; y++) for (const x of [Math.floor((a + b) / 2), Math.floor((a + b + 1) / 2)]) if (c.get(x, y)) { under = y; break find; }
    const lift = rim - (under + 1);
    sp = { crown: sp.crown.map(([y, x0, x1]) => [y - lift, x0, x1] as Span), brim: [] };
  }
  const dark = new Mat(m.lo, { lo: mix(m.lo, SHADE, 0.3) });
  const xs = [...sp.crown, ...sp.brim].flatMap(([, a, b]) => [a, b]);
  const loX = Math.min(...xs), hiX = Math.max(...xs);
  if (sp.crown.length) c.part(sp.crown, m, 't', 'r');
  if (kind === 'beanie') {
    c.part(sp.brim, new Mat(m.hi, { lo: m.base }), 't', 'b');
    for (const [y, a, b] of sp.brim) for (let x = a + 1; x < b; x += 2) c.px(x, y, m.base);
    const top = sp.crown[0];
    c.rect(top[1], top[0], top[2], top[0], mix(m.hi, WHITE, 0.5));            // the bobble
  } else if (kind === 'cowboy') {
    c.part(sp.brim, dark, 't', 'b');
    for (const [y, a, b] of sp.crown) if (y === 6) c.rect(a, y, b, y, mix(m.lo, SHADE, 0.55));   // the band
  } else if (kind === 'tophat') {
    c.part(sp.brim, dark, 't', 'b');
    const band = m.base[0] + m.base[1] + m.base[2] < 380 ? mix(m.base, WHITE, 0.7) : mix(m.base, SHADE, 0.7);
    for (const [y, a, b] of sp.crown) if (y === 5 || y === 6) c.rect(a, y, b, y, band);
  } else if (kind === 'crown') {
    let i = 0;
    for (let x = loX + 3; x < hiX - 1; x += 4, i++) {
      c.px(x, 6, rgb(i % 2 === 0 ? '#e5484d' : '#4f9cf0'));
      c.px(x, 5, m.hi);
    }
  } else if (kind === 'bucket') {
    c.part(sp.brim, dark, 't', 'b');
  } else if (kind === 'party') {
    sp.crown.forEach(([y, a, b], k) => { if (k === 3 || k === 6) c.rect(a, y, b, y, mix(m.base, WHITE, 0.8)); });
    const top = sp.crown[0];
    c.rect(top[1], top[0], top[2], top[0], rgb('#ffd84a'));
  } else if (kind === 'headband') {
    c.part(sp.brim, m, 't', 'b');
  }
}

/** A hat's crown, for a headset to sit on. A party hat has none to give: it stands on the hair, and the hair is still
 *  the top of the head. */
const crownOf = (p: Person, view: 'f' | 's'): Span[] | null => (p.hat && p.hat !== 'party' && HATS[p.hat][view].crown.length ? HATS[p.hat][view].crown : null);

/** The top row of the hair or hat, which is where a headset's band goes. */
function hairTop(p: Person): number {
  const crown = crownOf(p, 'f');
  if (crown) return minY(crown);
  if (hairHidden(p)) return 6;
  const st = styleOf(p);
  const spans = [...st.f.spans, ...(st.fx?.spans ?? [])];
  return spans.length ? minY(spans) : 6;
}

function drawBeard(c: Cv, p: Person, view: 'f' | 's', y1 = 99) {
  const kind = p.beard;
  if (!kind) return;
  if (kind === 'scruff' && p.scruff && p.beardMat) {         // stubble with texture: a tint, darker flecks, heavier at the jaw
    const sc = p.scruff, col = p.beardMat.base;
    for (const [y, x0, x1] of BEARDS[sc.mask][view]) for (let x = x0; x <= x1; x++) {
      const fleck = pm(x + 2 * y, 4) === 0;
      c.tint(x, y, col, Math.min(0.9, sc.tint + (fleck ? 0.32 : 0) + (y >= 20 ? 0.10 : 0)));
    }
    if (sc.stache) c.part(view === 'f' ? [[17, 9, 16], [18, 9, 10], [18, 15, 16]] : [[17, 5, 9], [18, 8, 9]], p.beardMat, '', '');
    return;
  }
  const beard = BEARDS[kind];
  if (!beard) return;
  if (kind === 'boxed' && p.beardMat) {
    const fade = view === 'f' ? [...BOXED_FADE_F, ...BOXED_FADE_F.map(([y, a, b, t]) => [y, 25 - b, 25 - a, t] as const)] : BOXED_FADE_S;
    for (const [y, a, b, t] of fade) for (let x = a; x <= b; x++) c.tint(x, y, p.beardMat.base, t);
    c.part(beard[view].filter((s) => s[0] <= y1), p.beardMat, '', 'b');
    for (let x = view === 'f' ? 9 : 5; x < (view === 'f' ? 17 : 9); x++) c.px(x, 17, p.beardMat.hi);   // the moustache catches the light
    return;
  }
  if (kind === 'stubble') {
    for (const [y, x0, x1] of beard[view]) for (let x = x0; x <= x1; x++) c.tint(x, y, p.stubble, 0.30);
  } else if (p.beardMat) {
    c.part(beard[view].filter((s) => s[0] <= y1), p.beardMat, 't', 'b');
  }
}

const TALK_DARK: RGB = [70, 22, 30], TALK_TONGUE: RGB = [196, 84, 92], BEARD_MOUTH: RGB = [104, 44, 48], TEETH: RGB = [250, 246, 240];
const mouthOf = (p: Person): RGB => (BEARDED.includes(p.beard ?? '') ? BEARD_MOUTH : mix(p.skin.lo, [170, 70, 70], 0.55));

/** The mouth at rest. Front: the middle of the face is x 11..14 on row 18. Side: x 6..8. */
function drawMouth(c: Cv, p: Person, front: boolean) {
  const m = mouthOf(p), k = p.mouth;
  if (front) {
    if (k === 'open') { c.rect(12, 18, 13, 19, TALK_DARK); return; }
    if (k === 'small') { c.px(12, 18, m); c.px(13, 18, m); return; }
    for (let x = 11; x < 15; x++) c.px(x, 18, m);
    if (k === 'smile' || k === 'tongue') { c.px(10, 17, m); c.px(15, 17, m); }
    if (k === 'smirk') c.px(15, 17, m);
    if (k === 'frown') { c.px(10, 19, m); c.px(15, 19, m); }
    if (k === 'tongue') { c.px(12, 19, TALK_TONGUE); c.px(13, 19, TALK_TONGUE); }
    if (k === 'grin') {                                                       // a row of teeth
      c.px(10, 18, m); c.px(15, 18, m);
      for (let x = 11; x < 15; x++) { c.px(x, 18, TEETH); c.px(x, 19, m); }
    }
  } else {
    if (k === 'open') { c.rect(6, 18, 7, 18, TALK_DARK); c.px(7, 19, m); return; }
    if (k === 'small') { c.px(6, 18, m); return; }
    c.px(6, 18, m); c.px(7, 18, m);
    if (k === 'smile' || k === 'smirk' || k === 'tongue') c.px(8, 17, m);
    if (k === 'frown') c.px(8, 19, m);
    if (k === 'tongue') c.px(6, 19, TALK_TONGUE);
    if (k === 'grin') { c.px(6, 18, TEETH); c.px(7, 18, TEETH); c.px(8, 18, m); c.px(6, 19, m); c.px(7, 19, m); }
  }
}

function drawBrows(c: Cv, p: Person, front: boolean) {
  const k = p.brows, col = p.brow;
  if (k === 'none') return;
  if (front) {
    const dots: number[][] =
      k === 'thin' ? [[8, 11], [9, 11], [10, 11], [15, 11], [16, 11], [17, 11]]
      : k === 'arched' ? [[7, 11], [8, 10], [9, 10], [10, 11], [15, 11], [16, 10], [17, 10], [18, 11]]
      : k === 'stern' ? [[7, 10], [8, 10], [9, 11], [10, 11], [15, 11], [16, 11], [17, 10], [18, 10]]
      : k === 'soft' ? [[7, 11], [8, 11], [9, 10], [10, 10], [15, 10], [16, 10], [17, 11], [18, 11]]
      : k === 'mono' ? range(7, 19).map((x) => [x, 11])
      : [7, 15].flatMap((x0) => range(x0, x0 + 4).map((x) => [x, 11]));
    for (const [x, y] of dots) c.px(x, y, col);
    if (k === 'thick') for (const x of [8, 9, 10, 15, 16, 17]) c.px(x, 10, col);
  } else {
    const dots: number[][] =
      k === 'thin' ? [[7, 11], [8, 11], [9, 11]]
      : k === 'arched' ? [[7, 11], [8, 10], [9, 10], [10, 11]]
      : k === 'stern' ? [[7, 11], [8, 11], [9, 10], [10, 10]]
      : k === 'soft' ? [[7, 10], [8, 10], [9, 11], [10, 11]]
      : k === 'mono' ? range(6, 11).map((x) => [x, 11])
      : range(7, 11).map((x) => [x, 11]);
    for (const [x, y] of dots) c.px(x, y, col);
    if (k === 'thick') { c.px(8, 10, col); c.px(9, 10, col); }
  }
}

/** The colour of a shut eye. On very dark skin a dark line would not show, so the lid catches the light instead. */
const lidOf = (p: Person): RGB => (lum(p.skin.base) < 80 ? mix(p.skin.base, [255, 236, 214], 0.42) : EYE);

/** One open eye, its left dot at ex. `out` is +1 when the outer corner is on the right, -1 on the left. Every dot
 *  that is part of the eye goes in `dots`, so lenses know not to tint it. */
function drawEye(c: Cv, p: Person, ex: number, out: number, dots: Set<string>) {
  const col = p.eyeCol, k = p.eyes;
  const dot = (x: number, y: number, tone: RGB) => { c.px(x, y, tone); dots.add(`${x},${y}`); };
  const block = (y0: number) => { for (let y = y0; y <= 15; y++) { dot(ex, y, col); dot(ex + 1, y, col); } };
  const outer = out > 0 ? ex + 2 : ex - 1;
  const dark = lum(p.skin.base) < 105;                                       // dark eyes on dark skin need the white of the eye to show
  const white: RGB = [238, 230, 222];
  if (k === 'big') { block(12); dot(ex, 12, WHITE); if (dark) { dot(outer, 13, white); dot(outer, 14, white); } }
  else if (k === 'small') { block(14); dot(ex, 14, WHITE); if (dark) dot(outer, 14, white); }
  else if (k === 'dot') { const x = out > 0 ? ex : ex + 1; dot(x, 14, col); dot(x, 15, col); if (dark) dot(x + out, 14, white); }
  else if (k === 'sleepy') { block(14); dot(ex, 13, mix(p.skin.lo, SHADE, 0.3)); dot(ex + 1, 13, mix(p.skin.lo, SHADE, 0.3)); if (dark) dot(outer, 14, white); }
  else if (k === 'happy') { const lid = lidOf(p); dot(ex - 1, 14, lid); dot(ex, 13, lid); dot(ex + 1, 13, lid); dot(ex + 2, 14, lid); }
  else if (k === 'round') { block(13); for (let y = 13; y <= 15; y++) dot(outer, y, [250, 250, 255]); }
  else {
    block(13); dot(ex, 13, WHITE);
    if (dark) { dot(outer, 14, white); if (k !== 'lashes') dot(outer, 13, white); }
    if (k === 'lashes') { dot(outer, 12, EYE); dot(outer, 13, EYE); }
    if (k === 'tired') { c.px(ex, 16, mix(p.skin.lo, SHADE, 0.25)); c.px(ex + 1, 16, mix(p.skin.lo, SHADE, 0.25)); }
  }
}

/** Freckles, a scar and the like. Front cheeks are x 5..8 and 17..20; the side shows one cheek, x 9..11. */
function drawMarks(c: Cv, p: Person, front: boolean) {
  const sk = p.skin, k = p.marks;
  if (k === 'freckles') {
    const col = mix(sk.lo, [150, 88, 58], 0.5);
    for (const [x, y] of front ? [[6, 16], [8, 16], [7, 17], [17, 16], [19, 16], [18, 17]] : [[9, 16], [11, 16], [10, 17]]) c.px(x, y, col);
  } else if (k === 'blush') {
    for (const x of front ? [5, 6, 7, 8, 17, 18, 19, 20] : [9, 10, 11]) c.tint(x, 16, [240, 96, 110], 0.4);
    for (const x of front ? [6, 7, 18, 19] : [10]) c.tint(x, 17, [240, 96, 110], 0.25);
  } else if (k === 'mole') {
    c.px(front ? 17 : 10, 17, mix(sk.lo, INK, 0.6));
  } else if (k === 'scar') {
    const col = lum(sk.base) > 120 ? mix(sk.base, [196, 96, 100], 0.6) : mix(sk.base, [236, 170, 160], 0.55);
    for (let y = 9; y <= 17; y++) if (y < 13 || y > 15 || !front) c.px(front ? 19 : 11, y, col);
    if (front) for (let y = 13; y <= 15; y++) c.px(19, y, col);
  } else if (k === 'plaster') {
    const x0 = front ? 6 : 9;
    c.rect(x0, 16, x0 + 2, 17, [250, 240, 224]);
    c.px(x0 + 1, 16, [226, 198, 166]); c.px(x0 + 1, 17, [226, 198, 166]);
    c.px(x0 + 2, 17, [222, 208, 196]);
  } else if (k === 'whiskers') {
    const col = mix(sk.lo, INK, 0.5);
    for (const [x, y] of front ? [[5, 16], [6, 16], [5, 18], [6, 18], [19, 16], [20, 16], [19, 18], [20, 18]] : [[9, 16], [10, 16], [9, 18], [10, 18]]) c.px(x, y, col);
  } else if (k === 'paint') {
    if (front) { c.rect(6, 16, 9, 16, p.accent); c.rect(16, 16, 19, 16, p.accent); c.rect(7, 17, 8, 17, mix(p.accent, WHITE, 0.4)); c.rect(17, 17, 18, 17, mix(p.accent, WHITE, 0.4)); }
    else { c.rect(8, 16, 11, 16, p.accent); c.rect(9, 17, 10, 17, mix(p.accent, WHITE, 0.4)); }
  } else if (k === 'vitiligo') {                                             // patches of much lighter skin: round one eye, by the mouth, on the jaw
    const pale: RGB = [250, 226, 212];
    for (const [x, y] of front ? [[17, 12], [18, 12], [19, 12], [18, 13], [19, 13], [19, 14], [6, 18], [7, 18], [7, 19], [8, 19], [5, 17]] : [[10, 12], [11, 12], [11, 13], [12, 13], [7, 18], [8, 18], [8, 19]]) c.tint(x, y, pale, 0.7);
  } else if (k === 'bindi') {
    if (front) { c.px(12, 12, [200, 40, 60]); c.px(13, 12, [200, 40, 60]); }
    else c.px(5, 12, [200, 40, 60]);
  }
}

