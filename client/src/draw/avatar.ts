const FW = 48, FH = 48;   // frame size
/** Rows of headroom above every 48-dot frame, drawn to with a negative y: for whatever stands taller than the frame
 *  (a party hat on top of somebody's hair, their head at the top of a jump). The frame is the bottom 48 rows of its cell. */
export const SPRITE_UP = 18;
const UP = SPRITE_UP;
const FEET = 44;          // y of the bottom row of the shoes
const CX = 24;            // body centre: columns 23 and 24 are the middle pair
const HW = 26, HH = 34;   // the head layer. Front skull: x 4..21, y 6..21; chin at y 21.
/** An empty frame, with its headroom. */
const blank = () => new Cv(FW, FH, UP);

// drink: a drink held at the chest x2 (breathing), lifted for a sip x2. The drink itself is laid on by the app (see
// marksOf for where). drink_sit: the same four, sitting.
export const SPRITE_ROWS = ['walk_down', 'walk_left', 'walk_right', 'walk_up', 'idle', 'sit_front', 'sit_side', 'sit_back', 'gaming', 'sleep', 'gaming_back', 'dance', 'cheer', 'reach', 'punch', 'floored', 'drink', 'drink_sit', 'sweep', 'call', 'roast', 'roast_side', 'roast_back'] as const;
export type SpriteRow = (typeof SPRITE_ROWS)[number];

const EYE: RGB = [38, 28, 46];
const GOLD: RGB = [232, 192, 74];
const pm = (a: number, n: number) => ((a % n) + n) % n;       // a remainder that never goes negative
const range = (a: number, b: number) => { const out: number[] = []; for (let i = a; i < b; i++) out.push(i); return out; };
/** Rows y0 up to (not including) y1, each from x0 to x1. */
const span = (x0: number, y0: number, y1: number, x1: number): Span[] => range(y0, y1).map((y) => [y, x0, x1] as Span);
const lum = (c: RGB) => 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2];
/** The same rows on the other side of the body. */
const across = (spans: Span[]): Span[] => spans.map(([y, a, b]) => [y, 2 * CX - 1 - b, 2 * CX - 1 - a] as Span);

